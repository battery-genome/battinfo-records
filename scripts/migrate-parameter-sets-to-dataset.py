#!/usr/bin/env python3
"""Move the claim-batch parameter sets from spec/ to dataset/ (ruled 2026-10-11).

Parameter sets mint under ``https://w3id.org/battinfo/dataset/{uid}`` with a
new seed (BIG-MAP/BattINFO#436). The records published under ``spec/`` are
republished as new records that supersede them: each record here gets the
IRI BattINFO mints for its own target, scope and name, and names the old
``spec/`` IRI in ``supersedes``. Nothing else in the record changes.

BPX parameter files (``*--bpx`` records with ``parameters_sha256``) are NOT
handled here: they are regenerated by ``scripts/ingest-bpx-file.py``, which
mints them from the file's parameters.

Run from the repo root with a BattINFO environment at #436 or later:

    ../BattINFO/.venv/Scripts/python scripts/migrate-parameter-sets-to-dataset.py [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RECORD_DIR = REPO / "records" / "parameter-set"
SPEC_PREFIX = "https://w3id.org/battinfo/spec/"
TARGETS = ("material_kind", "material_spec_id", "cell_spec_id")


def new_iri(body: dict) -> str:
    """The dataset/ IRI BattINFO mints for this claim batch's target, scope and name."""
    from battinfo.api import create_parameter_set

    target = {key: body[key] for key in TARGETS if key in body}
    minted = create_parameter_set(
        name=body["name"],
        scope=body.get("scope"),
        **({"electrode_polarity": body["electrode_polarity"]} if body.get("electrode_polarity") else {}),
        # The id depends only on target, scope, polarity and name; one claim
        # satisfies the builder.
        claims=[{"parameter": "density", "quantity": {"value": 1.0, "unit": "g/cm3"},
                 "provenance_class": "literature"}],
        validate=False,
        **target,
    )
    return minted["parameter_set"]["id"]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    from battinfo.validate import validate_record_report

    changed = 0
    for path in sorted(RECORD_DIR.glob("*/record.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        body = record["parameter_set"]
        if "parts" in body:
            continue  # a parameter file: ingest-bpx-file.py regenerates it
        old = body["id"]
        if not old.startswith(SPEC_PREFIX):
            continue  # already moved
        iri = new_iri(body)
        uid = iri.rsplit("/", 1)[-1]
        body["id"] = iri
        body["short_id"] = uid.replace("-", "")[:6]
        body["supersedes"] = old
        report = validate_record_report(record, policy="publisher")
        if not report.ok:
            raise SystemExit(f"{path.parent.name}: invalid after the move: {report.errors}")
        print(f"{path.parent.name:40s} {old.rsplit('/', 1)[-1]} -> {uid}")
        changed += 1
        if not args.dry_run:
            path.write_text(json.dumps(record, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"{changed} record(s) {'would move' if args.dry_run else 'moved'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
